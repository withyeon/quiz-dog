function loadEnv() {
  const envPath = process.env.ENV_FILE || path.join(process.cwd(), '.env.local')
  if (!fs.existsSync(envPath)) return
  for (const line of fs.readFileSync(envPath, 'utf8').split('\n')) {
    const match = line.match(/^([^=]+)=(.*)$/)
    if (!match) continue
    let value = match[2].trim()
    if ((value.startsWith('"') && value.endsWith('"')) || (value.startsWith("'") && value.endsWith("'"))) {
      value = value.slice(1, -1)
    }
    process.env[match[1].trim()] = value
  }
}

loadEnv()

const supabaseUrl = process.env.NEXT_PUBLIC_SUPABASE_URL
const supabaseKey = process.env.SUPABASE_SECRET_KEY || process.env.SUPABASE_SERVICE_ROLE_KEY
if (!supabaseUrl || !supabaseKey) {
  console.error('Missing NEXT_PUBLIC_SUPABASE_URL or SUPABASE_SECRET_KEY/SUPABASE_SERVICE_ROLE_KEY.')
  process.exit(1)
}

const supabase = createClient(supabaseUrl, supabaseKey)

async function findOwnerId() {
  for (let page = 1; page < 50; page++) {
    const { data, error } = await supabase.auth.admin.listUsers({ page, perPage: 200 })
    if (error) throw error
    const user = data.users.find((u) => u.email?.toLowerCase() === OWNER_EMAIL)
    if (user) return user.id
    if (data.users.length < 200) break
  }
  throw new Error(`${OWNER_EMAIL} 계정을 찾지 못했습니다.`)
}

async function seed() {
  const ownerId = await findOwnerId()
  console.log(`owner: ${ownerId}`)

  const only = process.env.ONLY_SETS?.split(',')

  for (const { questions, ...set } of sets) {
    if (only && !only.some((n) => set.id.endsWith(`-${n}`))) continue
    console.log(`Seeding ${set.title} (${questions.length} questions)`)

    const { error: setError } = await supabase.from('question_sets').upsert(
      { ...set, subject: '기타', grade: '기타', tags: ['한방병리', '변증'], owner_id: ownerId, is_public: false },
      { onConflict: 'id' },
    )
    if (setError) throw setError

    const { error: deleteError } = await supabase.from('questions').delete().eq('set_id', set.id)
    if (deleteError) throw deleteError

    const { error: questionError } = await supabase
      .from('questions')
      .insert(questions.map((question) => ({ set_id: set.id, ...question })))
    if (questionError) throw questionError

    const { count, error: countError } = await supabase
      .from('questions')
      .select('*', { count: 'exact', head: true })
      .eq('set_id', set.id)
    if (countError) throw countError
    console.log(`  → ${count ?? 0} questions`)
  }

  console.log('Seed complete.')
}

seed().catch((error) => {
  console.error('Seed failed:', error)
  process.exit(1)
})
